"""Golden prompts: the exact messages each phase sends, sync and batch.

Until the prompt-builder merge the two paths built their
prompts separately (`ProviderCall`/`ProviderCallAugment` for sync,
`providers.requests.build_request` for batch) and differed: create's user turn
was `"{start} '{subject}'"` on one and `"{start}'{subject}'"` on the other,
sync augment dropped `prompt_start_text`, sync fix/verify carried no persona,
`\\n` against `\\n\\n`. The merge made `ProviderCall.build_request`
delegate to the batch builder after an A/B; the sync goldens were rewritten
then, and now equal batch's but for `custom_id` and `metadata`
(`test_sync_and_batch_send_the_same_prompts`).

Each phase runs through its real entry point (`execute_prompt.run_phase` for
sync, `cli.main(["run", "--batch", ...])` for batch) against the
`fake_provider`, on one small corpus: an Egyptian History listing a discovery
and a city, a valid discovery atom (verify), a discovery `_ERROR` sentinel
(fix), and a seed city with two period names (expand, append). List
neighbours are on (3, as the live pack sets them) and one subject has a create
note. The fixtures under `tests/fixtures/golden_prompts/` were written from
v0.1.19 (the `sync_*` ones rewritten at the merge); they are not
regenerated by this module.

Also pinned: the schema text each vendor appends to the system prompt
(`schema_suffix_sha256`), which v0.2.0 moved into one place.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from universe_builder import settings, store
from universe_builder.domains.history.models.city import City
from universe_builder.domains.history.models.discovery import Discovery
from tests.factories import minimal_payload

GOLDEN = Path(__file__).parent / "fixtures" / "golden_prompts"
MODEL = "gpt-5-nano"
PHASES_SYNC = ("create", "fix", "verify", "expand", "append")
PHASES_BATCH = ("create", "fix", "verify", "expand")


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _reply(request) -> str:
    """A valid payload of whatever shape was asked for."""
    return json.dumps(minimal_payload(request.schema_model))


def _write(atom_type, subject, payload, model=MODEL, error=False):
    path = store.path_for(atom_type, None, subject, model)
    if error:
        path = store.error_path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(payload if isinstance(payload, str) else json.dumps(payload), encoding="utf-8")
    return path


@pytest.fixture
def corpus(workspace, tmp_path, monkeypatch, fake_provider):
    seed = tmp_path / "HISTORY_list.txt"
    seed.write_text("Egyptian History\n", encoding="utf-8")
    monkeypatch.setattr(settings, "HISTORY_LIST", seed)
    notes = tmp_path / "create_notes.txt"
    notes.write_text("[Egyptian History]\ndiscovery | Papyrus | The writing material, not the plant.\n",
                     encoding="utf-8")
    monkeypatch.setattr(settings, "CREATE_NOTES", notes)
    monkeypatch.setattr(settings, "CREATE_NEIGHBOURS", 3)
    history = {"people": [], "events": [], "artifacts": [],
               "discoveries": ["Papyrus", "Shaduf (irrigation tool)", "Calendar", "Faience"],
               "cities": ["Memphis", "Thebes (Luxor)"]}
    _write("history", "Egyptian History", history)
    # verify's input: a valid discovery
    _write("discovery", "Calendar", minimal_payload(Discovery, shortSummary="A calendar."))
    # fix's input: a sentinel holding a payload that failed validation
    _write("discovery", "Faience", '{"name": {"common": "Faience"}, "shortSummary": 3}', error=True)
    # expand's and append's input: a seed city with two period names
    _write("city", "Thebes (Luxor)", minimal_payload(City, cityPeriodsOfHistory=["New Kingdom", "Late Period"]))
    fake_provider.script(*([_reply] * 50))
    yield workspace
    # `run --batch` opens a journal run and nothing closes it; do not leak it.
    from universe_builder import journal

    journal.end_run()


def _capture(requests) -> list:
    rows = []
    for r in requests:
        rows.append({
            "custom_id": r.custom_id,
            "model": r.model,
            "schema_model": r.schema_model.__name__,
            "max_tokens": r.max_tokens,
            "system": r.system,
            "user": r.user,
            "examples": [{"user": e.user, "assistant_sha256": _sha(e.assistant_json)} for e in r.examples],
            "metadata": {k: v for k, v in sorted(r.metadata.items())},
        })
    return sorted(rows, key=lambda row: (row["schema_model"], row["user"], row["custom_id"] or ""))


def run_sync(phase, fake_provider) -> list:
    from universe_builder import execute_prompt

    atoms = ["discovery", "city"]
    execute_prompt.run_phase(phase, atoms=atoms, model=MODEL)
    return _capture(fake_provider.requests)


def run_batch(phase, fake_provider) -> list:
    from universe_builder import cli

    assert cli.main(["run", "--phase", phase, "--batch", "--model", MODEL]) == 0
    return _capture(fake_provider.requests)


def _golden(name):
    return json.loads((GOLDEN / f"{name}.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("phase", PHASES_SYNC)
def test_the_sync_prompts_are_the_golden_ones(corpus, fake_provider, phase):
    assert run_sync(phase, fake_provider) == _golden(f"sync_{phase}")


@pytest.mark.parametrize("phase", PHASES_BATCH)
def test_the_batch_prompts_are_the_golden_ones(corpus, fake_provider, phase):
    assert run_batch(phase, fake_provider) == _golden(f"batch_{phase}")


@pytest.mark.parametrize("phase", PHASES_BATCH)
def test_sync_and_batch_send_the_same_prompts(phase):
    """One prompt builder. Everything but the routing is equal —
    `custom_id` (sync: the subject; batch: `<atom>-<n>-<slug>`) and
    `metadata` (batch adds `operation`, and `target`/period routing for the
    payload phases). `append` has no batch path."""
    def prompt(rows):
        return [{k: v for k, v in row.items() if k not in ("custom_id", "metadata")} for row in rows]

    assert prompt(_golden(f"sync_{phase}")) == prompt(_golden(f"batch_{phase}"))
    [sync_fix], [batch_fix] = _golden("sync_fix"), _golden("batch_fix")
    assert sync_fix["custom_id"] != batch_fix["custom_id"]
    assert "operation" in batch_fix["metadata"] and "operation" not in sync_fix["metadata"]


SCHEMA_SUFFIX = _golden("schema_suffix") if (GOLDEN / "schema_suffix.json").exists() else {}


def schema_suffixes() -> dict:
    """sha256 of the text each vendor appends to the system prompt, per schema."""
    from universe_builder.providers.anthropic_provider import AnthropicProvider
    from universe_builder.providers.google_provider import GoogleProvider
    from universe_builder.providers.openai_provider import OpenAIProvider
    from universe_builder.providers.types import LLMRequest
    from universe_builder.domains.history.models.city import CityExpanded, Population

    out = {}
    for model in (Discovery, City, CityExpanded, Population):
        request = LLMRequest(model=MODEL, schema_model=model, system="S", user="U")
        openai = object.__new__(OpenAIProvider)
        anthropic = object.__new__(AnthropicProvider)
        google = object.__new__(GoogleProvider)
        wire = {
            "openai": openai._messages(request)[0]["content"],
            "anthropic": "".join(b["text"] for b in anthropic._system_blocks(request)),
            "google": google._system_instruction(request),
        }
        for vendor, text in wire.items():
            assert text.startswith("S")
            out[f"{vendor}:{model.__name__}"] = _sha(text[1:])
    return out


def test_the_schema_text_each_vendor_appends_is_the_golden_one():
    assert schema_suffixes() == SCHEMA_SUFFIX
