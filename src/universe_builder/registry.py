_PACKS: dict[str, Callable[[], DomainPack]] = {}
#: The module each pack was registered from — the default home of its
#: migrations (`DomainPack.migrations_package`).
_PACK_MODULES: dict[str, str] = {}

_active: Optional[DomainPack] = None
#: The domain the engine runs, defaulted from UNIVERSE_BUILDER_DOMAIN at import so the choice
#: does not depend on which module gets imported first. `set_active_pack`
#: overrides it (tests, an explicit switch). Read here rather than in `atoms` so
#: `active_pack()` is correct for any caller — `cli.cmd_periods` consults it
#: directly, and used to see the default because it had not imported `atoms`.
_active_name: str = os.environ.get("UNIVERSE_BUILDER_DOMAIN") or "history"


#: The entry-point group an installed distribution registers a pack under:
#:
#:     [project.entry-points."universe_builder.domains"]
#:     formulary = "my_package.pack"
#:
#: The target is a module that calls `register_pack` on import — in which case
#: the entry-point name must equal the name the module registers — or a
#: callable builder (`() -> DomainPack`), which is registered under the
#: entry-point name and must therefore NOT also register itself on import
#: (both would register, and two packs sharing atom names are refused). This
#: is how a pack outside this package is found by name. An entry point is
#: tried before the bundled `universe_builder.domains.<name>`, so an installed
#: distribution naming `history` would shadow the bundled pack.
ENTRY_POINT_GROUP = "universe_builder.domains"


def bundled_pack_names() -> List[str]:
    """The packs shipped under `universe_builder.domains`, by directory, without importing
    them — for the "unknown domain" message, which used to list only what had
    already been imported, i.e. nothing."""
    import pkgutil

    from universe_builder import domains

    return sorted(m.name for m in pkgutil.iter_modules(domains.__path__) if m.ispkg)


def _discover(name: str) -> str:
    """Find the pack called `name` and return the name it registered under.

    Four places are tried, in order, and the first that yields a pack wins:

    1. already registered (an earlier import, or a test's `register_pack`);
    2. a dotted module path (`name` contains a dot): the module is imported
       and is expected to register itself. It may register under a different
       name than the path — `UNIVERSE_BUILDER_DOMAIN=my_pack.history` registering
       "history" — so the name that *appeared* is what is returned;
    3. an entry point in `ENTRY_POINT_GROUP` called `name`;
    4. the bundled `universe_builder.domains.<name>` package.

    A missing pack is not an error here — the caller reports the unknown
    name with the list it knows — but a pack that *exists and fails to
    import* propagates, so a broken dependency inside a domain reads as
    what it is rather than as "unknown domain".
    """
    if name in _PACKS:
        return name
    if "." in name:
        before = set(_PACKS)
        importlib.import_module(name)
        if name in _PACKS:
            return name
        appeared = set(_PACKS) - before
        if not appeared:
            # Imported earlier in this process, so nothing new registered:
            # the pack is whichever one that module registered then.
            appeared = {n for n, module in _PACK_MODULES.items() if module == name}
        if len(appeared) == 1:
            return appeared.pop()
        if not appeared:
            raise KeyError(f"{name} imported but registered no domain pack")
        raise KeyError(f"{name} registered {sorted(appeared)}; name one of them")
    for entry_point in metadata.entry_points(group=ENTRY_POINT_GROUP):
        if entry_point.name != name:
            continue
        before = set(_PACKS)
        loaded = entry_point.load()
        if name not in _PACKS:
            if callable(loaded):
                register_pack(name, loaded)
            else:
                appeared = sorted(set(_PACKS) - before)
                raise KeyError(
                    f"entry point {ENTRY_POINT_GROUP}:{name} loaded {loaded!r}, which "
                    + (f"registered {appeared}, not {name!r}: the entry-point name must "
                       f"equal the pack's name" if appeared
                       else "neither registered a pack nor is a builder"))
        return name
    try:
        importlib.import_module(f"universe_builder.domains.{name}")
    except ImportError as e:
        if e.name != f"universe_builder.domains.{name}":
            raise
    return name


def register_pack(name: str, builder: Callable[[], DomainPack]) -> None:
    """Register a pure builder, rejecting atom-name collisions among loaded packs.

    Builders may run more than once. This guards shared migration keys and
    folders in this process; separate data roots are still required for domains
    that run independently with potentially overlapping names.
    """
    candidate = builder()
    names = [spec.name for spec in candidate.all_specs()]
    if len(names) != len(set(names)):
        raise ValueError(f"Duplicate atom names in domain pack {name!r}")
    # Registration is the only moment a bad link path is still cheap. After it,
    # the path is read against raw payload dicts, where "no such field" and
    # "empty list" are the same answer and the mistake is silent for months.
    validate_link_paths(candidate)
    validate_evidence_paths(candidate)
    validate_summary_paths(candidate)
    for other_name, other_builder in _PACKS.items():
        if other_name == name:
            continue
        collisions = set(names) & {s.name for s in other_builder().all_specs()}
        if collisions:
            raise ValueError(
                f"Domain packs {name!r} and {other_name!r} share atom names: {sorted(collisions)}; "
                "atom folders and migration keys must be unique across packs"
            )
    _PACKS[name] = builder
    _PACK_MODULES[name] = builder.__module__


def migrations_package(pack: DomainPack) -> str:
    """Where `pack`'s migration steps live: its own declaration, else the
    `.migrations` subpackage beside the module that registered it."""
    declared = getattr(pack, "migrations_package", None)
    if declared:
        return declared
    module = _PACK_MODULES.get(pack.name)
    if module is None:
        # Never registered through `register_pack` (a test's stand-in): the
        # bundled convention is the only guess left.
        return f"universe_builder.domains.{pack.name}.migrations"
    return f"{module}.migrations"


def pack_provenance() -> Dict[str, Optional[str]]:
    """The active pack's name, the module that registered it, and the
    distribution (name, version) that module was installed from.

    For the journal's `run.json` (`journal.provenance`), so a run says which
    release of the pack produced it — a pack installed from its own
    repository is a separate distribution and its version moves independently
    of the engine's. Found through the `universe_builder.domains` entry point whose
    module is the registering one (the pack may have registered itself on
    import, before any discovery); a bundled pack is the engine's own
    distribution; anything else falls back to the installed-package map.
    Unknown parts are None.
    """
    pack = active_pack()
    module = _PACK_MODULES.get(pack.name)
    origin: Dict[str, Optional[str]] = {"name": pack.name, "module": module,
                                        "distribution": None, "version": None}
    top = (module or "").split(".")[0]
    if not top:
        return origin
    for entry_point in metadata.entry_points(group=ENTRY_POINT_GROUP):
        dist = getattr(entry_point, "dist", None)
        if (entry_point.name == pack.name and dist is not None
                and entry_point.module.split(".")[0] == top):
            origin["distribution"], origin["version"] = dist.name, dist.version
            return origin
    names = (["universe_builder"] if top == "universe_builder"
             else metadata.packages_distributions().get(top) or [])
    if names:
        try:
            origin["distribution"], origin["version"] = names[0], metadata.version(names[0])
        except metadata.PackageNotFoundError:
            pass
    return origin


def _known_names() -> List[str]:
    return sorted(set(_PACKS) | set(bundled_pack_names()))


def set_active_pack(name: str) -> None:
    """Choose which registered pack the engine runs. Clears the cache.

    A pack that has not registered yet is discovered by `_discover`: a dotted
    module path, an `universe_builder.domains` entry point, or the bundled
    `universe_builder.domains.<name>` — so a domain outside this package is picked up by
    name without this module importing it.
    """
    global _active, _active_name
    resolved = _discover(name)
    if resolved not in _PACKS:
        raise KeyError(f"Unknown domain pack {name!r}. Known: {', '.join(_known_names())}")
    _active_name = resolved
    _active = None


def active_pack() -> DomainPack:
    """The pack the engine is currently running (built once, then cached).

    Honours `_active_name` (defaulted from UNIVERSE_BUILDER_DOMAIN), auto-importing the
    domain module if the pack has not registered yet — so an env-selected domain
    resolves correctly even for a caller that never imported `universe_builder.atoms`."""
    global _active, _active_name
    if _active is None:
        resolved = _discover(_active_name)
        if resolved not in _PACKS:
            raise KeyError(
                f"Unknown domain pack {_active_name!r} (from UNIVERSE_BUILDER_DOMAIN?). "
                f"Known: {', '.join(_known_names())}"
            )
        _active_name = resolved
        _active = _PACKS[_active_name]()
    return _active
