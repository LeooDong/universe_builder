"""The one declarative registry: what atom types exist and how each behaves.

Before this module the same facts were spread across five hand-maintained
tables that had to be edited in lock-step to add or reshape an atom —
`atoms.class_mapping`, `prompt_config.json`, the `History` topic-list fields,
`providers/registry._schema_models`, and `atoms.STAGE_MODELS` — with
`tests/test_config.py` existing only to catch them drifting apart. A test that
guards a duplication is a duplication that should not exist.

Here an atom is declared once, as an `AtomSpec`, and everything else is
*derived*: the runtime `atom_mapping` (including the `expand_*`/`append_*`
variants), `class_mapping`, the batch schema registry, the stage-shape
resolution, and the list of base atoms the create pass generates. A `DomainPack`
groups the specs for one problem domain plus its index atom (the seed that lists
what work exists). History is the pack shipped today; a second pack — a
medications formulary, say — is new `AtomSpec`s and models, never an edit here.

The derivations live in `atoms.py`, which reads `active_pack()`. This module is
pure data + dataclasses; it imports models but nothing that imports it, so it
sits below `atoms`, `topics`, `config` and the provider layer in the graph.
"""

from __future__ import annotations

import importlib
import os
from importlib import metadata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, FrozenSet, List, Optional, Tuple, Type, Union

from pydantic import BaseModel

#: A predicate over a raw payload dict, and the class to load it as when true.
StagePredicate = Callable[[dict], bool]


@dataclass(frozen=True)
class ExpandSpec:
    """How to expand one atom's list field of names into a list of objects.

    `entry_model` is the schema of a single expanded entry (e.g. `Population`);
    `expanded_model` is the whole atom once expanded (e.g. `CityExpanded`). They
    are different shapes and both are load-bearing — writing entry objects into
    the seed class is B7, which silently made the whole city corpus unreadable.
    `prompt_start`/`example` are what the augment call uses; the augment atom's
    reported class is the *seed* model, matching the old `expand_city` entry.
    """

    list_field: str
    entry_model: Type[BaseModel]
    expanded_model: Type[BaseModel]
    prompt_start: str
    example: Optional[Union[str, List[str]]] = None


@dataclass(frozen=True)
class AppendSpec:
    """How to generate a supplementary atom to be merged into the base one."""

    model: Type[BaseModel]
    prompt_start: str
    example: Optional[Union[str, List[str]]] = None


@dataclass(frozen=True)
class OperationSpec:
    """A domain's own CLI verb: `universe_builder <name> [flags]`.

    `handler(args) -> int` receives the parsed namespace, as `cmd_*` does.
    `add_arguments(parser)` declares the verb's flags on the subparser the
    CLI builds for it; `help` is the one line `--help` shows. The CLI once
    knew one operation by name (`periods`) and carried its flags in core, so a
    second domain verb was an argparse error — this is what made
    the history pack's `media` and `signals` possible without core learning
    what they are. A bare callable in `DomainPack.operations` still works and
    means "no flags".
    """

    handler: Callable
    help: str = ""
    add_arguments: Optional[Callable] = None


@dataclass(frozen=True)
class AtomSpec:
    """One atom type, declared once.

    `plural` is the field on the index atom that lists this atom's topics (and
    the on-disk folder is `name`). `stages` reproduces `STAGE_MODELS`: a payload
    whose shape matches a predicate loads as that class rather than `model`.
    """

    name: str
    model: Type[BaseModel]
    prompt_start: str
    plural: Optional[str] = None
    example: Optional[Union[str, List[str]]] = None
    stages: Tuple[Tuple[StagePredicate, Type[BaseModel]], ...] = ()
    expand: Optional[ExpandSpec] = None
    append: Optional[AppendSpec] = None


@dataclass(frozen=True)
class DomainPack:
    """Everything the engine needs to run one problem domain.

    `index` is the seed atom that lists topics (History for the history domain);
    it is generated by its own phase and read by every other pass, so it is an
    `AtomSpec` like the rest but singled out here because the create pass treats
    it as the source of work, not as work. `atoms` are the generated types.
    `response_models` are non-atom schemas a call may return that still need to
    be resolvable by name on the batch path (none for history — the expander
    `Population` is reached through its `ExpandSpec`).
    """

    name: str
    index: AtomSpec
    atoms: Tuple[AtomSpec, ...]
    response_models: Tuple[Type[BaseModel], ...] = ()
    #: Domain-specific CLI verbs, name -> `OperationSpec` (or a bare
    #: handler(args)->int, meaning no flags). The CLI builds one subparser per
    #: entry, so `universe_builder periods` is history's operation, not a core
    #: verb hardcoded to cities, and a domain that declares none simply has no
    #: such behaviour. A name that collides with a core verb is refused at
    #: parser build time. See `operation_specs`.
    operations: Dict[str, Union[Callable, OperationSpec]] = field(default_factory=dict)
    #: Where this domain's one-shot example JSON lives. A second domain ships its
    #: own examples, so the loader consults the *active* pack's dir rather than a
    #: single global one. When None the loader falls back to the bundled
    #: `settings.examples_dir(prompt_folder)` — but that package `prompts/examples/`
    #: dir is empty since history's examples moved to `domains/history/examples/`,
    #: so any real pack must set this (both shipped packs do); None
    #: now resolves to an empty dir, not to history's examples.
    examples_dir: Optional[Path] = None
    #: The domain persona prepended to every generating call. None means "use the
    #: package default base_system.txt" (the historian text history has always
    #: used), so history is unchanged and a new domain overrides it.
    base_system: Optional[str] = None
    #: The domain's name-identity file — links and scoped splits the data does
    #: not declare (`topics.load_aliases`). Identity is inherently per-domain (a
    #: city Thebes split for history; brand↔generic like Advil=ibuprofen for a
    #: medications domain), so each domain owns its own; None = no aliases.
    aliases_path: Optional[Path] = None
    #: Per-subject sentences for the create prompt, where a listed name means
    #: something lesser-known than the name suggests (`topics.load_create_notes`).
    #: None = no notes; a declared file that is missing or malformed stops create.
    create_notes_path: Optional[Path] = None
    #: How many list entries either side of a subject its create prompt names
    #: (`topics.list_neighbours`). 0 = none. A bare name loses what the index
    #: list knew by the company the entry keeps: on known misgenerations, most
    #: came back wrong bare and nearly all right with a few entries either side.
    create_neighbours: int = 0
    #: The seed list the index phase generates from (history: which civilisations
    #: to produce `History` atoms for). None = the phase has no bundled seed and a
    #: caller must supply subjects (e.g. `--list`).
    index_seed_path: Optional[Path] = None

    #: Wire *paths* containing names of other atoms: source -> path -> target.
    #:
    #: A path is dotted for nested objects (`birth.location.city`) and uses `[]`
    #: for a list of objects (`cityPeriodsOfHistory[].tradingPartners`). A bare
    #: field name is just a one-segment path, so every declaration written
    #: before paths existed still means what it meant.
    #:
    #: Paths are *wire* names — the alias, where a `WireModel` has one
    #: (`finderOrDiscoveror`, not `finderOrDiscoverer`) — because the index
    #: reads raw stored JSON, not validated models.
    #:
    #: Every path is checked against its source model at registration
    #: (`validate_link_paths`). That check exists because the failure it catches
    #: is invisible: `index.build` reads a path off a payload dict, and a path
    #: that does not exist yields exactly what a genuinely empty field yields.
    #: The four `person` relations were declared as top-level `parents`,
    #: `children`, `spouses`, `otherRelatives` while living under `family`, and
    #: produced zero edges from 2,706 stored mentions for as long as they had
    #: been declared, with nothing anywhere reporting a problem.
    link_fields: Dict[str, Dict[str, str]] = field(default_factory=dict)

    #: Where each atom type keeps the *place* and the *date* that identify its
    #: subject, as dotted wire paths (no `[]`: these name one object, not a
    #: list). `lint.corroboration` compares two atoms field to matching field
    #: along them — never one atom's museum against the other's excavation
    #: site — and `sources.context_terms` reads `country`/`state` off the first
    #: coordinate path that has them. A type with no entry has no comparable
    #: evidence, and both consumers say so rather than guessing. Validated at
    #: registration: a coordinate path must end at a model with `latitude` and
    #: `longitude`, a date path at one with `year` and `era`.
    coordinate_paths: Dict[str, Tuple[str, ...]] = field(default_factory=dict)
    date_paths: Dict[str, Tuple[str, ...]] = field(default_factory=dict)
    #: Where each atom type keeps a prose summary of its subject, as dotted
    #: wire paths to a string, first non-empty wins. `duplicates --via model`
    #: shows ~300 characters of it beside the names, dates and places, so the
    #: judge can tell a subject from one it contains (v0.4.0). A type with no
    #: entry gets no summary. Validated at registration: each path must end at
    #: a field that can hold a string.
    summary_paths: Dict[str, Tuple[str, ...]] = field(default_factory=dict)
    #: Hosts whose pages are worth citing, best first. Not a whitelist —
    #: `sources` keeps anything that resolves — but ties break here and the
    #: search prompt asks for these. Empty means no preference.
    preferred_hosts: Tuple[str, ...] = ()
    #: Free (no model) subject-to-URL resolvers for `sources --via NAME`, name ->
    #: factory. A factory takes `per_atom=` and returns `ask(subject, atom_type,
    #: hints=()) -> [url]`, optionally with an `ask.prefetch(subjects)` method
    #: the command calls first. History ships a Wikipedia one; `search` (a
    #: paid web-search model) is core and always available.
    url_resolvers: Dict[str, Callable] = field(default_factory=dict)
    #: URLs a person rejected for one atom, never to be offered to it again by
    #: `sources` (`sources.load_rejected`): a TSV with the header `atom url
    #: reason date origin`, `atom` a `kind:hID`. None, or no file at the path,
    #: is no rejects; a malformed line stops `sources`. v0.4.0.
    rejected_sources_path: Optional[Path] = None
    #: v0.4.1: a pack's own reading of the index's memberships. Called by
    #: `index.build` (and `index.memberships()`, which every reader shares) with
    #: the raw memberships, `{context: {atom_type: {subject: "type:id" | None}}}`,
    #: one context per stored index atom; returns `(memberships, provenance)`:
    #: the memberships every consumer reads, and a JSON-able record of what was
    #: changed, written as `links.json`'s `folds` section when non-empty. The
    #: history pack resolves a folded line's index atom onto the lines it folds
    #: into, so that a fold keeps its own atom (it can be unfolded later) while
    #: no reader ever sees it as a line. None: memberships are the raw ones.
    membership_resolver: Optional[Callable[[dict], tuple]] = None
    #: v0.5.0: the pack's own operation texts, operation -> text, which win
    #: over the engine's `prompts/operations/<op>.txt`. A prompt experiment
    #: that changes one is promoted by a commit to the pack, which needs the
    #: pack to own them. Empty: the engine's files, as before.
    operation_texts: Dict[str, str] = field(default_factory=dict)
    #: v0.5.0, prompt experiments (`experiments`). Where the pack keeps its
    #: prompt variants, one folder each with a `variant.yaml`. None: none.
    variants_dir: Optional[Path] = None
    #: `(atom_type, subject, context, payload) -> {check: flags}`: free,
    #: deterministic checks of one generated atom, fewer flags better. None:
    #: an experiment reports the engine's generic metrics only.
    experiment_checks: Optional[Callable[..., Dict[str, int]]] = None
    #: `(atom_type, subject, context) -> text | None`: a reference the
    #: experiment judge reads both arms against, chosen from the *listed* name,
    #: never from either arm's output. None: an experiment cannot be judged.
    experiment_reference: Optional[Callable[..., Optional[str]]] = None
    #: The judge's rubric, prepended to the engine's pairwise instructions.
    experiment_rubric: Optional[str] = None
    #: v0.5.5: `(atom_type, subject, context) -> [(title, sentence, url)]`,
    #: possible reference articles for a subject, offered in its create prompt
    #: only by a prompt spec with `create_candidates` on (a variant; the live
    #: prompt never asks). The model is told they may be namesakes and to use
    #: one only if it is clearly this entry. Short by contract: a few titles
    #: and one sentence each. None: no candidates.
    create_candidates: Optional[Callable[..., list]] = None
    #: v0.5.8: offer `create_candidates` in the LIVE create prompt too (the
    #: pipeline's create, sync and batch), not only in a variant. Turned on by
    #: a pack once a variant with candidates has won its experiment.
    create_candidates_live: bool = False
    #: v0.5.8: the version of the candidates hook's behaviour (its filter),
    #: hashed into a prompt spec's fingerprint whenever candidates are on, so
    #: a changed hook never pools with the old one. Bump it with the hook.
    create_candidates_version: Optional[int] = None
    #: v0.5.8: checks reported per arm but left out of the check-flags
    #: guardrail (a measure, not a failure: e.g. "cites another article than
    #: the stored one", which a shadow cannot even read).
    experiment_report_only_checks: FrozenSet[str] = frozenset()
    #: Free identity sources for `lint --review F --via NAME`: name -> object
    #: with `resolve_titles(names) -> {name: (id, landed_title, ambiguous)}`, where
    #: `(None, landed, False)` means the source answered and has no such page; a
    #: name it could not look up (an outage, an error answer) is LEFT OUT, never
    #: reported as missing, so callers read absence as "unknown" (`.get`). A
    #: source may raise instead when it cannot run at all (the local one does).
    #: Also `subject_leads(subjects) -> {name: opening text}` and
    #: `identity_verdict(subject, alias, resolved) -> (verdict|None, why)`.
    #: Abstaining (None) is the expected answer whenever the source cannot be
    #: sure; the command shows the evidence to a person instead.
    identity_resolvers: Dict[str, object] = field(default_factory=dict)
    #: Words too common in this domain's names to suggest two entries are one
    #: thing (`topics.near_matches`): "temple" and "dynasty" for history,
    #: "tablet" and "hydrochloride" for a formulary.
    near_match_stopwords: FrozenSet[str] = frozenset()
    #: The package whose modules hold this domain's per-atom migration steps
    #: (`migrations._loaded` walks it). None means "`.migrations` beside the
    #: module that registered the pack", which is what a pack defined in its
    #: own package gets for free; set it when the steps live elsewhere.
    migrations_package: Optional[str] = None

    def operation_specs(self) -> Dict[str, OperationSpec]:
        """`operations` with every bare callable promoted to an `OperationSpec`,
        so the CLI and tests handle one shape."""
        specs = {}
        for name, op in self.operations.items():
            if isinstance(op, OperationSpec):
                specs[name] = op
            elif callable(op):
                specs[name] = OperationSpec(handler=op, help=(op.__doc__ or "").strip().split("\n")[0])
            else:
                raise TypeError(f"operation {name!r} of domain {self.name!r} is neither an "
                                f"OperationSpec nor a callable: {op!r}")
        return specs

    def all_specs(self) -> Tuple[AtomSpec, ...]:
        return (self.index, *self.atoms)


