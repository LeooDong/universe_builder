def _models_in(annotation) -> List[Type[BaseModel]]:
    """Every Pydantic model reachable through an annotation's type arguments.

    `Optional[Location]`, `List[Optional[str]]` and `List[Union[Population,
    str]]` all have to be seen through to whatever a path could descend into.
    """
    import typing

    found: List[Type[BaseModel]] = []
    stack = [annotation]
    seen = set()
    while stack:
        current = stack.pop()
        if id(current) in seen:
            continue
        seen.add(id(current))
        if isinstance(current, type) and issubclass(current, BaseModel):
            found.append(current)
            continue
        stack.extend(typing.get_args(current))
    return found


def _annotation_admits_str(annotation) -> bool:
    """Whether a leaf could hold a name — `str`, `Optional[str]`, `List[str]`."""
    import typing

    stack = [annotation]
    seen = set()
    while stack:
        current = stack.pop()
        if id(current) in seen:
            continue
        seen.add(id(current))
        if current is str:
            return True
        stack.extend(typing.get_args(current))
    return False


def _annotation_is_list(annotation) -> bool:
    """Whether a field holds a list, seen through `Optional`.

    `Optional[List[Population]]` is a list; `Optional[Birth]` is not. This is
    what tells a missing `[]` from a correct path, and both mistakes are
    otherwise silent — they validate and then yield nothing at read time.
    """
    import typing

    stack = [annotation]
    seen = set()
    while stack:
        current = stack.pop()
        if id(current) in seen:
            continue
        seen.add(id(current))
        origin = typing.get_origin(current)
        if origin in (list, tuple, set, frozenset):
            return True
        if origin is typing.Union:
            stack.extend(typing.get_args(current))
    return False


def _roots_of(spec: AtomSpec) -> List[Type[BaseModel]]:
    """Every on-disk shape one atom type can have.

    Validating against `spec.model` alone is not enough: a city is stored as
    `City` before expansion and `CityExpanded` after, and the `Population`
    entries a path like `cityPeriodsOfHistory[].tradingPartners` descends into
    exist only in the expanded shape. `stages` and the expand spec are where the
    other shapes are declared, so they are part of the model here too.
    """
    roots = [spec.model]
    roots.extend(model for _, model in spec.stages)
    if spec.expand:
        roots.append(spec.expand.expanded_model)
    return roots


def validate_link_paths(pack: "DomainPack") -> None:
    """Raise if any `link_fields` path does not exist on its source model.

    Checks that every segment resolves by *wire* name, that `[]` is only used
    where the field really is a list, and that the leaf could hold a string.
    Raises `ValueError` naming the pack, the path and the offending segment.
    """
    by_name = {spec.name: spec for spec in pack.all_specs()}
    for source, paths in pack.link_fields.items():
        spec = by_name.get(source)
        if spec is None:
            raise ValueError(
                f"{pack.name}: link_fields names unknown atom type {source!r}")
        for path, target in paths.items():
            if target not in by_name:
                raise ValueError(
                    f"{pack.name}: link {source}.{path} points at unknown atom "
                    f"type {target!r}")
            current = _roots_of(spec)
            segments = path.split(".")
            for position, raw in enumerate(segments):
                listed = raw.endswith("[]")
                segment = raw[:-2] if listed else raw
                # Every current shape is consulted, not just the first that
                # matches. A city is `City` before expansion and `CityExpanded`
                # after, and both declare `cityPeriodsOfHistory` — as
                # `List[str]` and `List[Union[Population, str]]` respectively.
                # Stopping at the first would reject
                # `cityPeriodsOfHistory[].tradingPartners`, which is correct on
                # every expanded city on disk.
                matches = [field_info
                           for model in current
                           for field_name, field_info in model.model_fields.items()
                           if (field_info.alias or field_name) == segment]
                if not matches:
                    shapes = ", ".join(sorted({m.__name__ for m in current}))
                    raise ValueError(
                        f"{pack.name}: link path {source}.{path} has no wire field "
                        f"{segment!r} on {shapes}. Paths are dotted for nested "
                        f"models (e.g. 'birth.location.city') and use '[]' for a "
                        f"list of objects; a nested field declared flat reads as "
                        f"an empty list and yields no edges."
                    )
                # The `[]` marker must match the field's shape. Both mistakes
                # are silent at read time — traversal meets a list where it
                # wants a dict, or the reverse, and yields nothing — which is
                # precisely the class of failure this function exists to catch.
                # A leaf list of *strings* (`notableFigures`) needs no marker:
                # traversal yields each entry, and always has.
                is_list = any(_annotation_is_list(m.annotation) for m in matches)
                last = position == len(segments) - 1
                if listed and not is_list:
                    raise ValueError(
                        f"{pack.name}: link path {source}.{path} marks {segment!r} "
                        f"with '[]' but it is not a list; traversal would find no "
                        f"list to walk and yield no edges")
                if not listed and not last and is_list:
                    raise ValueError(
                        f"{pack.name}: link path {source}.{path} descends through "
                        f"{segment!r}, which is a list, so it needs '[]' "
                        f"({segment}[].…); without it traversal meets a list where "
                        f"it wants an object and yields no edges")
                if last:
                    if not any(_annotation_admits_str(m.annotation) for m in matches):
                        raise ValueError(
                            f"{pack.name}: link path {source}.{path} ends at a "
                            f"field that cannot hold a name "
                            f"({matches[0].annotation!r})")
                else:
                    current = [model
                               for match in matches
                               for model in _models_in(match.annotation)]
                    if not current:
                        raise ValueError(
                            f"{pack.name}: link path {source}.{path} descends "
                            f"through {segment!r}, which holds no nested model")


def _models_at(spec: AtomSpec, path: str) -> List[Type[BaseModel]]:
    """The models a dotted wire path (no `[]`) ends at, across every stored shape.

    Raises `ValueError` naming the missing segment, so a pack that misspells a
    field is refused at registration instead of yielding "no evidence" for
    every atom for as long as nobody notices.
    """
    current = _roots_of(spec)
    for segment in path.split("."):
        matches = [field_info
                   for model in current
                   for field_name, field_info in model.model_fields.items()
                   if (field_info.alias or field_name) == segment]
        if not matches:
            shapes = ", ".join(sorted({m.__name__ for m in current}))
            raise ValueError(
                f"path {spec.name}.{path} has no wire field {segment!r} on {shapes}")
        if any(_annotation_is_list(m.annotation) for m in matches):
            raise ValueError(
                f"path {spec.name}.{path} descends through {segment!r}, which is "
                f"a list; evidence paths name one object, not a list")
        current = [model for match in matches for model in _models_in(match.annotation)]
        if not current:
            raise ValueError(
                f"path {spec.name}.{path} ends at {segment!r}, which holds no "
                f"nested model")
    return current


def validate_evidence_paths(pack: "DomainPack") -> None:
    """Raise if a coordinate or date path does not exist or ends at the wrong shape.

    A coordinate path must end at a model with `latitude` and `longitude`; a
    date path at one with `year` and `era`. The check is by field name rather
    than by class so a domain with its own `Location`-like model still
    qualifies.
    """
    by_name = {spec.name: spec for spec in pack.all_specs()}
    for label, table, wanted in (("coordinate", pack.coordinate_paths, ("latitude", "longitude")),
                                 ("date", pack.date_paths, ("year", "era"))):
        for atom_type, paths in table.items():
            spec = by_name.get(atom_type)
            if spec is None:
                raise ValueError(
                    f"{pack.name}: {label}_paths names unknown atom type {atom_type!r}")
            for path in paths:
                try:
                    leaves = _models_at(spec, path)
                except ValueError as e:
                    raise ValueError(f"{pack.name}: {label} {e}") from None
                for leaf in leaves:
                    names = {info.alias or name for name, info in leaf.model_fields.items()}
                    missing = [w for w in wanted if w not in names]
                    if missing:
                        raise ValueError(
                            f"{pack.name}: {label} path {atom_type}.{path} ends at "
                            f"{leaf.__name__}, which has no {', '.join(missing)}")


def validate_summary_paths(pack: "DomainPack") -> None:
    """Raise if a `summary_paths` entry names an unknown type, a missing
    field, a list on the way, or ends at a field that cannot hold a string."""
    by_name = {spec.name: spec for spec in pack.all_specs()}
    for atom_type, paths in pack.summary_paths.items():
        spec = by_name.get(atom_type)
        if spec is None:
            raise ValueError(f"{pack.name}: summary_paths names unknown atom type {atom_type!r}")
        if isinstance(paths, str):
            raise ValueError(f"{pack.name}: summary_paths[{atom_type!r}] is a string; "
                             f"it must be a tuple of dotted paths")
        for path in paths:
            parent, _, leaf = path.rpartition(".")
            try:
                models = _models_at(spec, parent) if parent else _roots_of(spec)
            except ValueError as e:
                raise ValueError(f"{pack.name}: summary {e}") from None
            matches = [info for model in models for name, info in model.model_fields.items()
                       if (info.alias or name) == leaf]
            if not matches:
                shapes = ", ".join(sorted({m.__name__ for m in models}))
                raise ValueError(f"{pack.name}: summary path {atom_type}.{path} has no wire "
                                 f"field {leaf!r} on {shapes}")
            if not any(_annotation_admits_str(m.annotation) for m in matches):
                raise ValueError(f"{pack.name}: summary path {atom_type}.{path} ends at a "
                                 f"field that cannot hold text ({matches[0].annotation!r})")


