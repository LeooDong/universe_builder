"""Where a phase's work list comes from.

Two callers needed the same answer and each wrote its own version:
`execute_prompt.run_base_atom_calls` walked the History files inline, and
`run_batch._subjects_from_history` walked them again. They disagreed in a way
that matters — the batch one de-duplicated across History files and the pipeline
one did not.

De-duplicating is the correct behaviour, and not merely for tidiness. Two
civilisations can both list Alexandria, and content-addressed ids (step 3b) map
one subject to one path. So a duplicated topic is two calls racing for a single
file — exactly the collision `operations._support.persist` has to defend against
— and the second call is paid for twice to produce a file the first already
wrote.

The context each topic came from is kept, because it is not decoration: the
create pass puts "The context is Egyptian History!" into the system text, which
genuinely changes the answer for an ambiguous subject. First occurrence wins, so
a topic listed by two civilisations keeps the one that mentioned it first rather
than silently acquiring a second identity.
"""

