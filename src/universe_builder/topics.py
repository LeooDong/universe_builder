def load_aliases(path=None) -> tuple:
    """Parse the alias file into `AliasGroup`s. A missing file is no aliases.

    The format is line-based so a human maintains it without tooling:

        # comment
        [Egyptian History]                  # following lines apply here only
        Thebes (Luxor) = Thebes = Waset
        [*]                                 # back to every context
        Amarna (Akhetaten) = Tell el-Amarna

    An unreadable file is an error but not a stop: grouping without aliases is
    exactly the behaviour the pipeline had before the file existed, so a bad
    file degrades to yesterday rather than aborting today's run.
    """
    if path is None:
        # `settings.ALIASES_LIST` is an override knob (default None, set by tests
        # and any explicit --aliases); otherwise the active pack's own alias file.
        path = alias_files.aliases_path()
    if path is None:
        return ()  # a domain that declares no aliases groups on declared links alone
    try:
        text = Path(path).read_text(encoding="utf-8")
    except FileNotFoundError:
        return ()
    except (OSError, UnicodeDecodeError) as e:
        log.error("Cannot read the alias file %s (%s); grouping runs without it", path, e)
        return ()

    groups: list = []
    for declaration in alias_files.parse_alias_text(text):
        if not declaration.names:
            log.warning("%s:%d declares no names; line skipped", Path(path).name, declaration.number)
            continue
        groups.append(AliasGroup(names=declaration.names, scope=declaration.scope,
                                 provenance=declaration.provenance))

    _warn_on_alias_contradictions(groups, Path(path).name)
    return tuple(groups)


def _warn_on_alias_contradictions(groups, filename: str) -> None:
    """Flag a name claimed twice within one scope, at load rather than at use.

    Two groups of the *same* scope claiming one key contradict each other, and
    every entry matching that key will be left ungrouped by the ambiguity rule.
    That outcome is safe but silent-ish; saying so when the file is read points
    at the line to fix. A key shared between a global and a scoped group is not
    flagged — that is the refinement pattern, where the scoped line wins inside
    its civilisation and the global one everywhere else.
    """
    seen: dict = {}
    for group in groups:
        scope = name_key(group.scope) if group.scope else None
        for key in group.keys():
            slot = (key, scope)
            if slot in seen and seen[slot] != group.names[0]:
                log.warning(
                    "%s: %r appears in two groups of the same scope (%r and %r); "
                    "entries matching it will be left ungrouped",
                    filename, key, seen[slot], group.names[0],
                )
            seen.setdefault(slot, group.names[0])


class CreateNotesError(ValueError):
    """The create-notes file cannot be trusted; nothing should be created."""


def load_create_notes(path=None) -> dict:
    """Parse the domain's create-notes file: {(atom type or "*", scope key or
    None, subject key): note}.

    A create prompt carries only the bare name and the context, so a name that
    means something lesser-known in this list comes back as the famous thing:
    history's "Later Han dynasty" (947–951) was generated as the Eastern Han.
    A note is one sentence added to that one subject's prompt, and only that
    one's — every other prompt is unchanged. Format, sectioned like the alias
    file:

        # comment
        [Chinese History]
        polity | Later Han dynasty | The Five Dynasties Later Han (947–951), not the Eastern Han.
        [*]
        work | Heracles | Euripides's tragedy, not the hero.

    The first field is an atom type or `*`. Unlike the alias file, a bad file
    is an error, not a degradation: a note that silently fails to load is a
    misgeneration made again, and paid for. A declared file that is missing is
    the same error; a pack that declares none has no notes.
    """
    if path is None:
        path = settings.CREATE_NOTES or getattr(active_pack(), "create_notes_path", None)
        if path is None:
            return {}
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as e:
        raise CreateNotesError(f"cannot read the create-notes file {path}: {e}") from e

    types = set(atom_mapping)
    notes: dict = {}
    scope: Optional[str] = None
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            inner = line[1:-1].strip()
            scope = None if inner in ("", "*") else name_key(inner)
            continue
        fields = [f.strip() for f in line.split("|")]
        where = f"{path.name}:{number}"
        if len(fields) != 3 or not all(fields):
            raise CreateNotesError(f"{where}: expected `type | subject | note`, got {line!r}")
        atom_type, subject, note = fields
        if atom_type != "*" and atom_type not in types:
            raise CreateNotesError(f"{where}: unknown atom type {atom_type!r}; known: {sorted(types)}")
        slot = (atom_type, scope, name_key(subject))
        if slot in notes:
            raise CreateNotesError(f"{where}: a second note for {subject!r} in the same scope and type")
        notes[slot] = note
    return notes


def create_note(atom_type: str, subject: str, context: Optional[str] = None, notes=None) -> Optional[str]:
    """The note for this subject's create prompt, or None.

    The most specific line wins: this type in this context, then any type in
    this context, then this type everywhere, then any type everywhere. Matched
    on the folded subject — the spelling the atom is generated under — not on
    its aliases, so a note follows the one file it is about.
    """
    if notes is None:
        notes = load_create_notes()
    if not notes:
        return None
    key = name_key(subject)
    scope = name_key(context) if context else None
    for slot in ((atom_type, scope, key), ("*", scope, key), (atom_type, None, key), ("*", None, key)):
        if slot in notes:
            return notes[slot]
    return None


class ListIndex:
    """Each context's index list per atom type, read once: what
    `list_neighbours` needs for a whole batch without re-reading every index
    atom per subject."""

    def __init__(self, atom_type: str):
        self.atom_type = atom_type
        self.plural = next((s.plural for s in active_pack().atoms if s.name == atom_type), None)
        self.lists: dict = {}
        if self.plural:
            for path in _history_files():
                try:
                    payload = store.read_json(path)
                except OSError:
                    continue
                entries = payload.get(self.plural) if isinstance(payload, dict) else None
                if isinstance(entries, list):
                    self.lists.setdefault(name_key(context_of(Path(path).name)),
                                          [e for e in entries if isinstance(e, str)])
        self.groups = load_aliases()
        self.titles = {name_key(line): line for line in civilisations()}
        # Which spelling each listed entry is created as, by the work list's
        # own grouping (`from_history`'s arguments): the exact answer to "where
        # does this subject sit in that list". A name match is not: the Roman
        # list's `Oea (Tripoli)` shares a name with the Ottoman `Tripoli
        # (Lebanon)` and is a different topic.
        self.assigned: dict = {}
        if self.plural:
            group_occurrences(
                ((t.subject, t.context) for t in raw_occurrences(atom_type)),
                prefer=lambda subject: has_real_atom(atom_type, subject),
                aliases=self.groups,
                assignments=self.assigned,
            )

    def position(self, subject: str, context_key: str) -> Optional[int]:
        """Where `subject` (as the work list emits it) sits in this context's
        list: the first entry the grouping assigns to it, else its own spelling."""
        entries = self.lists.get(context_key) or []
        for i, entry in enumerate(entries):
            if self.assigned.get((entry, context_key)) == subject:
                return i
        return entries.index(subject) if subject in entries else None

    def contexts_of(self, subject: str) -> list:
        """Every context whose list has an entry created as `subject`."""
        return [ctx for ctx in self.lists if self.position(subject, ctx) is not None]


def _series(names: list) -> str:
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def list_neighbours(atom_type: str, subject: str, context: Optional[str], k: Optional[int] = None,
                    index: Optional[ListIndex] = None) -> Optional[str]:
    """One sentence naming the entries either side of `subject` in its
    context's index list, or None (no context, not found, or k = 0).

    The subject is found by the work list's own grouping (`ListIndex`), so an
    alias survivor finds its listed spelling and a namesake does not.

    The create prompt carries only the bare name, so a name meaning something
    lesser-known in this list comes back as the famous thing; its neighbours
    say which ("Later Han dynasty" between Later Jin and Later Zhou is the Five
    Dynasties state, not the Eastern Han). Only the first listing frames a
    create: a name two lists mean differently needs a scoped alias line.
    """
    if k is None:
        k = settings.CREATE_NEIGHBOURS if settings.CREATE_NEIGHBOURS is not None \
            else getattr(active_pack(), "create_neighbours", 0)
    if not k or not context:
        return None
    index = index or ListIndex(atom_type)
    context_key = name_key(context)
    entries = index.lists.get(context_key)
    if not entries:
        return None
    i = index.position(subject, context_key)
    if i is None:
        return None
    before, after = entries[max(0, i - k):i], entries[i + 1:i + 1 + k]
    where = f"In the {index.titles.get(context_key, context)} list of {index.plural}, this entry comes"
    if before and after:
        return f"{where} after {_series(before)}, and before {_series(after)}."
    if after:
        return f"{where} first, before {_series(after)}."
    if before:
        return f"{where} last, after {_series(before)}."
    return None


def create_instructions(atom_type: str, subject: str, context: Optional[str] = None, notes=None,
                        index: Optional[ListIndex] = None) -> Optional[str]:
    """What a subject's create prompt adds after the name: its list
    neighbours, then its note (`create_note`), or None for neither."""
    parts = [list_neighbours(atom_type, subject, context, index=index),
             create_note(atom_type, subject, context, notes)]
    if getattr(active_pack(), "create_candidates_live", False):
        # v0.5.8: a pack whose candidates variant won turns them on for every
        # create; the same builder the variant was tested with.
        from universe_builder.prompt_spec import candidates_block
        parts.append(candidates_block(atom_type, subject, context))
    parts = [p for p in parts if p]
    return "\n\n".join(parts) if parts else None


#: Words too common to imply two entries are the same thing are the domain's
#: (`DomainPack.near_match_stopwords`): "temple" and "dynasty" carry no identity
#: in a history corpus, "tablet" and "hydrochloride" none in a formulary.
def _stopwords():
    from universe_builder.registry import active_pack

    return active_pack().near_match_stopwords


def near_matches(subject: str, candidates) -> list:
    """Candidates that *might* be the same thing. Advisory only.

    Deliberately separate from `same_topic`, and deliberately looser. Grouping
    acts on names the data *declares* equivalent — `Thebes (Luxor)` says so
    outright — and acting on a guess there would silently merge two real places.
    This is for the report, where a wrong suggestion costs a reader two seconds
    and a missed one costs them a duplicate atom.

    Matches on a shared distinctive word, so `Akhetaten` and
    `Amarna (Akhetaten)` surface even though nothing links them by name. Common
    words are excluded or every "Temple of …" would match every other.
    """
    stop = _stopwords()

    def distinctive(text):
        return {w for w in name_key(text).split() if len(w) > 3 and w not in stop}

    wanted = distinctive(subject)
    if not wanted:
        return []
    return [c for c in candidates
            if c != subject and not same_topic(c, subject) and distinctive(c) & wanted]


def has_real_atom(atom_type: str, subject: str) -> bool:
    """Whether this topic has an atom worth keeping — not merely a file.

    `store.atoms_for` deliberately does not judge content, so it counts an
    `EmptyModel` placeholder: a 32-byte `{"error": "No data found"}` written at
    the atom's own path when a generation failed. Passing that straight to
    `group_synonyms`' `prefer` made a *failure* outrank a real atom — a topic
    with only a placeholder beat the sibling that had 5KB of validated content,
    and the real atom then had nothing in the work list pointing at it.

    `status --coverage` already made this judgement inline and correctly. Having
    it in one place is the point: the two disagreeing about what "has an atom"
    means is how the bug arose.
    """
    for path in store.atoms_for(atom_type, subject):
        # Never raises, for the same reason `_is_placeholder` does not: this runs
        # inside `group_synonyms`' `prefer`, which is called from a comprehension
        # with no guard around it, so an exception escapes and costs the caller
        # the *entire* work list rather than one atom. Reproduced once — one
        # binary city file and Thebes and Giza disappeared with it.
        #
        # A file that cannot be read is not a usable atom. Saying so keeps the
        # topic in the work list, which is the safe direction: it gets
        # regenerated rather than silently skipped.
        text = store.usable_text(path, unreadable=lambda p, e: log.warning(
            "Cannot read %s (%s); treating the topic as ungenerated", p.name, e))
        if not text:
            continue
        # Readable but unparseable is not a usable atom either — same safe
        # direction. The pipeline never writes malformed `.json` (writes are
        # atomic and serialise a validated model), so this guards only against
        # a corrupted or hand-edited file, which should be regenerated rather
        # than counted as present and skipped.
        try:
            json.loads(text)
        except ValueError:
            log.warning("Atom %s is not valid JSON; treating the topic as ungenerated",
                        path.name)
            continue
        return True
    return False


def stored_name_claims(atom_type: str) -> dict:
    """Every name the stored atoms of one type declare, folded -> the ids claiming it.

    The corpus knows things the work list does not. An atom records its own
    `name.common` and `name.otherNames`, and nothing read them: resolution ran
    against History-listed spellings, the alias file and filename topics only,
    so `Foundation of Memphis` could carry `Founding of Memphis` in its own
    `otherNames` — naming the rival atom outright — and no part of the system
    noticed. This is that missing half.

    **Ids come from the filename, never from hashing a declared name.**
    `store.atom_id(type, name.common)` would mint the id the atom *would* have
    had if it had been generated under that spelling, which for a duplicate is a
    different id than the file's own. `decompose_filename` asks the file who it
    is.

    **Keys are exact folded spellings — `name_key`, not `alias_keys`.** Splitting a
    stored parenthetical would have `Ancient Salamis (Cyprus)` claim the bare
    key `cyprus`, which is a country, not that city. The querying side may
    widen a probe (`_candidate_keys` tries the whole spelling, then head, then
    inner, most specific first); the claiming side must not, or an atom quietly
    annexes names it never declared.

    A key claimed by more than one atom is *not* an error here — it is the
    duplicate-atom report (`index.build`'s `duplicates` section). Resolution
    treats it as ambiguous and answers None, which is the standing rule: a name
    two atoms claim is not a guess to be made.
    """
    claims: dict = {}
    for path in store.iter_atoms(atom_type):
        try:
            payload = store.read_json(path)
        except OSError as e:
            # One unreadable file costs one file, as everywhere else in this
            # module. Never raise: callers iterate this inside comprehensions.
            log.warning("Cannot read %s (%s); it claims no names", path.name, e)
            continue
        if not isinstance(payload, dict) or store.is_empty_model(payload):
            continue
        try:
            atom_id = store.AtomName.decompose_filename(path.name).padded_id
        except ValueError:
            continue
        name = payload.get("name")
        if not isinstance(name, dict):
            continue
        for spelling in (name.get("common"), *(name.get("otherNames") or [])):
            if not isinstance(spelling, str):
                continue
            folded = name_key(spelling)
            # A one-letter declared name is a siglum or a foreign-script name
            # folded to nothing useful (`A` for Codex Alexandrinus, an Arabic
            # name starting with Ā), never an identity: it grouped a codex
            # with a palace.
            if folded and len(folded) > 1:
                claims.setdefault(folded, set()).add(atom_id)
    return claims


def duplicate_atoms(atom_type: str) -> list:
    """Stored atoms that declare a shared name — one subject, two files.

    Two atoms with different content ids for one subject pass every invariant
    the project has: `tests/test_corpus.py` counts files sharing an *id*, and
    these do not, because the ids derive from the two spellings the models
    happened to use. `Founding of Memphis` (gpt-4o-mini) and `Foundation of
    Memphis` (gpt-5-nano) are one event in two files for exactly that reason —
    Egyptian History has one atom per model by design, the two models spelled
    the topic differently, and `group_synonyms` joins only names that *declare*
    equivalence or that the alias file joins by hand.

    Returns `[{"name": key, "atom_ids": [...]}, ...]`, sorted, for the report.
    Detection only: nothing here retires a file.
    """
    return [{"name": folded, "atom_ids": sorted(ids)}
            for folded, ids in sorted(stored_name_claims(atom_type).items())
            if len(ids) > 1]


def listed_spellings(atom_type: str) -> dict:
    """History-listed subjects, grouped by the atom id each currently resolves to.

    An atom's `name.common` is what the *model* called the subject; the History
    lists hold what the *work list* calls it, and those differ more often than
    is comfortable — an atom generated for `Shaduf (irrigation tool)` can call
    itself simply `Shaduf`. Anything that has to keep the work list pointing at
    an atom (an alias line, say) must speak in listed spellings, or it joins two
    names nothing lists and leaves the listed one pointing at nothing.
    """
    resolve = subject_resolver(atom_type)
    found: dict = {}
    for topic in raw_occurrences(atom_type):
        atom = resolve(topic.subject, topic.context)
        if not atom:
            continue
        names = found.setdefault(atom, [])
        if topic.subject not in names:
            names.append(topic.subject)
    return found


def listed_keys_by_type() -> dict:
    """Every folded key any History atom lists, mapped to the types listing it.

    The alias file has no atom-type scope — a line joins names for every type at
    once — so a line written for one type can capture a name another type
    depends on. Writing `Unification of Upper and Lower Egypt = Unification of
    Upper and Lower Egypt by King Menes (Narmer)` for the *events* is enough to
    make `narmer` an ambiguous key for the *people*, because `alias_keys` splits
    that trailing parenthetical and the resulting group claims the bare name.
    This is how a caller checks before writing.
    """
    owners: dict = {}
    for spec in active_pack().atoms:
        if not spec.plural:
            continue
        for topic in raw_occurrences(spec.name):
            for key in alias_keys(topic.subject):
                owners.setdefault(key, set()).add(spec.name)
    return owners


def group_synonyms(subjects, prefer=None, aliases=()) -> list:
    """Collapse entries that declare a shared name, keeping one per group.

    The string form of `group_occurrences`, for callers with no contexts: every
    subject is treated as context-free, so scoped alias groups do not apply.
    See there for the rules.
    """
    pairs = group_occurrences(((s, None) for s in subjects), prefer=prefer, aliases=aliases)
    return [subject for subject, _ in pairs]


@dataclass
class _Declaration:
    """One claim that several names are one topic, as `group_occurrences`
    holds it (four parallel lists until v0.2.0).

    Two kinds. An *alias-file line* has its declared `names` (line order, the
    first the canonical spelling), its folded `scope` (None = every context)
    and `contexts` None. A *data declaration* — a parenthetical entry such as
    `Thebes (Luxor)` — has no names, no scope, and `contexts`: the folded
    contexts whose Histories made it.
    """

    keys: frozenset
    scope: Optional[str] = None
    names: tuple = ()
    contexts: Optional[set] = None
    #: A line's quoted names, folded (`AliasGroup.literal_keys`; v0.4.0).
    literals: frozenset = frozenset()

    @property
    def is_line(self) -> bool:
        """An alias-file line rather than a declaration in the data."""
        return bool(self.names)

    def speaks_for(self, folded_context: Optional[str]) -> bool:
        """Whether this claim reaches an entry listed under `folded_context`:
        a data declaration only within the Histories that made it, a line in
        its scope (or everywhere)."""
        if self.contexts is not None:
            return folded_context in self.contexts
        return self.scope is None or self.scope == folded_context


def group_occurrences(occurrences, prefer=None, aliases=(), assignments=None) -> list:
    """Collapse (subject, context) occurrences that share a declared name.

    Public since v0.2.0 (`_group_occurrences` is the old name): the work
    list's grouping, for a pack that must ask what a different set of
    occurrences or alias lines would group to.

    **Only a declaration creates a group, and groups never chain.** An earlier
    version union-found over every shared key, which merged transitively:

        ["Memphis (Mit Rahina)", "Mit Rahina (Saqqara)", "Saqqara"]
          -> ["Memphis (Mit Rahina)"]

    Saqqara vanished, joined to Memphis through a hop neither entry claims. One
    bad parenthetical was enough, and the loss was silent. So a parenthetical
    entry forms its *own* group and is never merged with another parenthetical;
    bare names then attach to the group that names them.

    Two kinds of declaration exist, and the alias file outranks the data.
    A line of `aliases` (see `load_aliases`) is a deliberate human claim: a
    parenthetical entry whose pair of names falls entirely inside one alias
    line is the *same* claim restated, not a rival, so it folds into that
    group — which is how `Amarna (Akhetaten)` in the data and
    `Amarna (Akhetaten) = Tell el-Amarna` in the file become one group rather
    than an ambiguity. A partial overlap does **not** fold: agreeing on one
    name while adding another is exactly the transitive chain the union-find
    version got wrong, so the entry stays its own declaration and the shared
    name becomes ambiguous, which is loud rather than lossy.

    **No claim crosses a civilisation boundary unless an alias line says so.**
    A data declaration speaks only for the Histories that made it: Egyptian
    History declaring `Thebes (Luxor)` claims an Egyptian bare `Thebes` and
    says nothing about a Greek one, which stands alone rather than silently
    merging into the Egyptian atom. A *global* alias line joins across
    civilisations (Alexandria in two Histories genuinely is one city); a
    *scoped* line claims only entries from its own civilisation, where it
    outranks unscoped claims — so Greek `Thebes` becomes `Thebes (Boeotia)`
    with its own identity while Egyptian `Thebes` still resolves onto
    `Thebes (Luxor)`. With neither line, the split is the default, because a
    wrong split is a visible duplicate and a wrong merge is an invisible hole.

    A name claimed by two declarations that survive those filters is ambiguous
    — nothing says which is meant — so it is left on its own and logged.
    Splitting there costs a duplicate atom; merging wrongly costs a topic that
    is never generated again, and the second is far harder to notice.

    `prefer` picks each group's survivor. The work list passes "already has a
    *real* atom", so a model answering `Thebes` resolves onto the stored
    `Thebes (Luxor)` rather than creating a sibling. An alias group widens the
    search to its *declared* names, so `Akhetaten` resolves onto a stored
    `Amarna (Akhetaten)` even when no current list spells it that way; with no
    stored atom anywhere, the line's first name is the spelling that gets
    generated, which is what keeps ids stable across differently-worded lists.

    `assignments`, when given a dict, is filled with
    `(subject, folded context) -> surviving subject` for every occurrence —
    which group each raw entry resolved into. The index needs it: membership
    attribution asks "which atom does *this listed spelling* point at", and
    the answer is its group's survivor, not the spelling itself.
    """
    occurrences = [(subject, context) for subject, context in occurrences]

    # Pass 0 — the alias file's lines declare first. Each is one group.
    decls: list = []          # declaration index -> _Declaration
    owner: dict = {}          # key -> set of declaration indices claiming it
    for group in aliases:
        keys = group.keys()
        if not keys:
            continue
        index = len(decls)
        decls.append(_Declaration(keys=keys, scope=name_key(group.scope) if group.scope else None,
                                  names=tuple(group.names), literals=group.literal_keys()))
        for key in keys:
            owner.setdefault(key, set()).add(index)
    lines = decls[:]          # the alias-file lines, in file order

    # Pass 1 — each parenthetical entry declares one group of its own names.
    # Keyed on the *claim*, not the occurrence: two History atoms both listing
    # `Thebes (Luxor)` make the same declaration twice, which is agreement, not a
    # conflict. Counting them as two claimants flagged every shared entry as
    # ambiguous and un-grouped it, so the city work list grew on the real corpus.
    declarations: dict = {}    # frozenset of the declared pair -> declaration index
    for subject, context in occurrences:
        # Identified by the *pair of names it declares*, not by its own spelling
        # (`_declared_pair`): keying on the full string made `Amarna (Akhetaten)`
        # and `Akhetaten (Amarna)` two declarations and flagged their own
        # entries as contradictory.
        pair = _declared_pair(subject)
        if pair is None:
            continue
        # A line that quotes this entry's whole spelling says its parenthetical
        # is part of the name, not a second name: the entry declares nothing
        # where that line speaks (v0.4.0). Pass 2 hands it to the line.
        folded_context = name_key(context) if context else None
        if any(name_key(subject) in line.literals and line.speaks_for(folded_context)
               for line in lines):
            continue
        index = declarations.get(pair)
        if index is None:
            folded_into = [i for i, line in enumerate(lines) if pair <= line.keys]
            if len(folded_into) == 1:
                index = folded_into[0]
            else:
                if not folded_into and any(pair & line.keys for line in lines):
                    log.warning(
                        "%r declares a pair that partially overlaps an alias line; "
                        "the entry keeps its own declaration — extend the line if "
                        "they really name one thing", subject,
                    )
                index = len(decls)
                decls.append(_Declaration(keys=frozenset(alias_keys(subject)), contexts=set()))
            declarations[pair] = index
        if decls[index].contexts is not None:
            # A data declaration speaks only for the civilisations whose
            # History made it — the same pair declared by two Histories is
            # agreement, and both may then attach their bare names.
            decls[index].contexts.add(name_key(context) if context else None)
        for key in alias_keys(subject):
            owner.setdefault(key, set()).add(index)

    # Pass 2 — assign every occurrence to a declaration, or to itself.
    assigned: dict = {}        # slot -> occurrences, in arrival order
    order: list = []

    def claim(slot, subject, context):
        if slot not in assigned:
            assigned[slot] = []
            order.append(slot)
        assigned[slot].append((subject, context))

    for subject, context in occurrences:
        keys = alias_keys(subject)
        if not keys:
            continue

        claimants = {i for key in keys for i in owner.get(key, set())}
        folded_context = name_key(context) if context else None
        # A data declaration claims only within the civilisations whose
        # Histories made it. Egyptian History declaring `Thebes (Luxor)` says
        # nothing about a *Greek* History's bare `Thebes` — with no alias line
        # present, that bare name used to join the foreign declaration and the
        # Greek city silently merged into the Egyptian atom. Crossing a
        # civilisation boundary is now something only an explicit alias line
        # can do: a global line joins (Alexandria genuinely is one city), a
        # scoped line splits, and with neither the entry stands alone — a
        # visible duplicate at worst, never an invisible merge.
        eligible = {i for i in claimants if decls[i].speaks_for(folded_context)}
        # An entry that declares its own pair is captured by an alias-file
        # group only when the group *contains* that pair. A group sharing
        # merely a name is a claim about a different thing: a Greek History
        # legitimately lists the Egyptian city as `Thebes (Luxor)`, and the
        # Greek-scoped `Thebes (Boeotia) = Thebes` line owns the bare name —
        # without this, scoped-outranks-unscoped let the line swallow an entry
        # that says outright it is somewhere else, and the Egyptian city
        # silently merged into Boeotia. The entry is more specific about
        # itself than any line that only brushes against it.
        pair = _declared_pair(subject)
        # A line quoting this entry's whole spelling claims it outright, and
        # nothing else does: the quotes say the parenthetical is part of the
        # name, so a line or declaration sharing only its head or inner name
        # is not a rival (v0.4.0).
        literal = {i for i in eligible if name_key(subject) in decls[i].literals}
        if literal:
            eligible = literal
        elif pair is not None:
            eligible = {i for i in eligible
                        if not decls[i].is_line or pair <= decls[i].keys}
        scoped = {i for i in eligible if decls[i].scope is not None}
        if scoped:
            eligible = scoped
        if len(eligible) == 1:
            claim(eligible.pop(), subject, context)
        elif not eligible:
            claim(name_key(subject), subject, context)
        else:
            # Two declarations name this entry and they disagree. Keep it.
            log.warning(
                "%r is claimed by %d different declarations; leaving it ungrouped "
                "rather than guessing which is meant", subject, len(eligible),
            )
            claim(name_key(subject), subject, context)

    # Pass 3 — one survivor per group.
    def pick(occurred):
        winner = occurred[0]
        for occurrence in occurred[1:]:
            if prefer is not None and prefer(occurrence[0]) and not prefer(winner[0]):
                log.debug("Grouping %r under %r", winner[0], occurrence[0])
                winner = occurrence
            else:
                log.debug("Grouping %r with %r", occurrence[0], winner[0])
        return winner

    def record_assignments(occurred, survivor):
        if assignments is None:
            return
        for subject, context in occurred:
            assignments[(subject, name_key(context) if context else None)] = survivor

    result: list = []
    for slot in order:
        occurred = assigned[slot]
        line = decls[slot] if isinstance(slot, int) and decls[slot].is_line else None
        if line is None:
            winner = pick(occurred)
            record_assignments(occurred, winner[0])
            result.append(winner)
            continue

        # An alias-file group: the declared names are candidates too, in line
        # order, so a stored atom is found under its own spelling even when no
        # current list uses it. First declared name is the canonical fallback.
        # A quoted name is tried, and generated, under the spelling inside its
        # quotes.
        names = tuple(unquote(name) for name in line.names)
        chosen = None
        if prefer is not None:
            holders, bypassed = [], []
            # A *scoped* line exists to give a bare name its own identity
            # inside one civilisation, so a stored atom under a bare name
            # other than the line's first cannot be what the line means:
            # Byzantine `Abydos (Hellespont) = Abydos` must not resolve onto
            # the Egyptian Abydos just because that city was generated under
            # the bare spelling. The first name is exempt (it is the spelling
            # the author wants, stored or not), and so is any parenthesised
            # name, which declares its own pair. Global lines keep the
            # corpus-wins rule in full: there the stored spelling is the same
            # thing by definition.
            scoped_line = line.scope is not None
            first_key = name_key(names[0])
            for name, key in lookup_order((*names, *(subject for subject, _ in occurred))):
                if (scoped_line and key != first_key
                        and not _PARENTHETICAL.match(name.strip())):
                    if prefer(name):
                        bypassed.append(name)
                    continue
                if prefer(name):
                    holders.append(name)
            if bypassed and not holders:
                log.warning(
                    "Scoped line %s: a stored atom sits under the bare %r, but a "
                    "scope's bare name belongs to another civilisation's atom "
                    "unless it leads the line; generating %r",
                    " = ".join(names), bypassed[0], names[0],
                )
            if len(holders) > 1:
                log.warning(
                    "One declared topic, %d stored atoms (%s); keeping %r — the "
                    "others are duplicates the alias file says should not exist",
                    len(holders), ", ".join(map(repr, holders)), holders[0],
                )
            if holders:
                chosen = holders[0]
        survivor = chosen if chosen is not None else names[0]
        record_assignments(occurred, survivor)
        result.append((survivor, occurred[0][1]))

    # Pass 4 — one file, one row. Two groups can emit the same spelling: an
    # Egyptian slot's canonical `Thebes (Luxor)` and a Greek History's own
    # `Thebes (Luxor)` entry standing alone (its pair kept it out of the Greek
    # line, its context kept it out of the Egyptian one). Equal normalised
    # topics are one content id and one path, so keeping both rows would be
    # two calls racing for a single file — the exact collision this module
    # exists to prevent. First occurrence keeps its context, as everywhere.
    deduped: list = []
    seen: set = set()
    for subject, context in result:
        identity = store.normalise_topic(subject)
        if identity not in seen:
            seen.add(identity)
            deduped.append((subject, context))
    return deduped


_group_occurrences = group_occurrences


def _is_placeholder(path) -> bool:
    """Whether `path` is a recorded failure rather than a History atom.

    **Never raises.** This runs inside `_history_files()`, which is a generator
    consumed outside `from_history`'s try/except, so an exception here escapes
    the loop entirely and costs the caller *every* History file — and since the
    files are sorted, one bad name early hides every good one after it. Adding
    the placeholder check put file I/O on that path for the first time, and a
    file that is not valid UTF-8 raised `UnicodeDecodeError` straight out of the
    iteration.

    A file that cannot be read is not a placeholder; say so and let the loader
    report it properly, per file, the way it always has.
    """
    return store.is_placeholder(path)


#: The History files every reader sees instead of the stored ones, for the
#: length of a `history_files_as` block; None outside one.
_history_files_override: Optional[tuple] = None


@contextmanager
def history_files_as(paths) -> Iterator[None]:
    """Make every reader see `paths` as the stored History files, for a block.

    The supported what-if (v0.2.0): the work lists
    (`raw_occurrences`, `from_history`, `needing_create`), the resolvers
    (`subject_resolver`, `listed_spellings`), `ListIndex`, `history_files`
    and `index.build`/`index.memberships` all learn which Histories exist
    from `_history_files`, which yields these instead. Nothing on disk
    changes. A substitute file must carry the name of the one it stands for:
    the context is read off the filename (`context_of`). Blocks nest; the
    previous set returns when one ends, however it ends.

    The history pack's `fold-history` gate is built on this ("would the work
    lists and memberships change with these Histories?"). Until v0.2.0 it
    reassigned `topics._history_files` itself, which still works: every
    reader looks the name up at call time (`tests/test_pack_contract.py`).
    """
    global _history_files_override
    previous = _history_files_override
    _history_files_override = tuple(Path(p) for p in paths)
    try:
        yield
    finally:
        _history_files_override = previous


def _history_files() -> Iterator:
    if _history_files_override is not None:
        yield from _history_files_override
        return
    # The index atom's folder/prefix, from the active pack: "history" for the
    # history domain, "formulary" for medications. Work discovery reads whatever
    # index atom the pack declares, not "history" by name.
    index_name = active_pack().index.name
    folder = store.dir_for(index_name)
    if not folder.exists():
        return
    for path in sorted(folder.iterdir()):
        # `<index>_...` only: the folder also holds _ERROR sentinels and, after a
        # fix pass, whatever else lands beside them.
        if not path.is_file() or not path.name.startswith(index_name) or store.is_error_path(path):
            continue
        # An `EmptyModel` placeholder is a recorded failure, not a History atom.
        # `persist` no longer writes one at the atom's path,
        # but placeholders predating that change still exist on disk, and without
        # this guard every caller got a five-error Pydantic dump per atom type,
        # five times over, for a file that was never going to parse. The augment
        # passes skip these with the same check.
        if _is_placeholder(path):
            log.debug("Skipping the empty placeholder %s", path.name)
            continue
        yield path


def raw_occurrences(atom_type: str) -> list[Topic]:
    """Every listed subject, per History file, before any grouping (public
    since v0.2.0; `_raw_occurrences` is the old name).

    Unreadable History files are skipped with an error rather than ending the
    pass — one bad file must not cost the run every topic behind it.
    """
    plural = atom_mapping[atom_type].plural
    if not plural:
        return []

    from universe_builder.index import load_atom_from_json  # index imports topics

    found: list[Topic] = []
    index_model = active_pack().index.model  # History for the history domain
    for path in _history_files():
        try:
            instance = load_atom_from_json(str(path), index_model)
        except Exception as e:  # noqa: BLE001
            log.error("Skipping unreadable history file %s: %s", path.name, e)
            continue

        context = context_of(path.name)
        for subject in getattr(instance, plural, None) or []:
            if subject and subject.strip():
                found.append(Topic(subject=subject.strip(), context=context))
    return found


_raw_occurrences = raw_occurrences


def from_history(atom_type: str) -> list[Topic]:
    """Every subject of `atom_type` listed by any stored History atom."""
    found = raw_occurrences(atom_type)

    # Group synonyms, not just exact repeats. Two History atoms from different
    # models name the same place differently — one says `Thebes (Luxor)`, another
    # says `Thebes` and `Luxor` as two entries — and an exact-match dedup treats
    # those as three topics, so three atoms get generated for one city. Prefer
    # whichever form already has an atom on disk, so new lists resolve onto the
    # corpus rather than growing siblings beside it. The alias file joins names
    # nothing in the data connects and keeps a shared name from crossing
    # civilisations — see `load_aliases`.
    kept = group_occurrences(
        ((t.subject, t.context) for t in found),
        prefer=lambda subject: has_real_atom(atom_type, subject),
        aliases=load_aliases(),
    )
    return [Topic(subject=subject, context=context) for subject, context in kept]


def subject_resolver(atom_type: str, aliases=None):
    """Build the name -> stored-atom-id resolver for one atom type.

    One resolver for every consumer — the index, reports, anything that wants
    to turn a free-text name into an atom — and it resolves *in the company of
    every History-listed spelling*, exactly as the work list does. That is not
    an optimisation: `Abydos (Abdju)` only resolves to the atom stored under
    bare `Abydos` because another History lists that spelling and grouping
    joins the two; bare `Narmer` only reaches `Narmer (Menes)` the same way.
    A name resolved on its own has none of that company and misses both — the
    first real index run left 17 listed subjects dangling that the work list
    knew perfectly well.

    Returns `resolve(name, context=None) -> Optional[str]` (a content id).
    Resolution order: this exact spelling as listed under this context; any
    listed spelling sharing a declared name (ambiguous shared names resolve to
    None rather than a guess — a context-free `Thebes` names two cities); the
    name itself if an atom sits under it; then, for a parenthetical name, its
    head and inner spellings alone; and finally the names the *stored atoms
    themselves declare* (`stored_name_claims`). None means nothing on disk
    answers — the caller decides whether that is a gap or just prose.

    **The payload claims are strictly a last resort, and that ordering is the
    safety property.** They are consulted only after every existing step has
    declined, so no answer this function gives today can change: the new index
    can turn a None into an id, never an id into a different id. The
    alternative — merging the two indexes and reconciling them — is what makes
    `None` dangerous, because `None` here means *both* "nothing answers" and
    "two things answer"; a merged lookup would let one index silently overrule
    the other's ambiguity in either direction. Ordering sidesteps that without
    needing to distinguish the two outcomes at this boundary. The cost is
    honest and recorded: 30 existing references whose names are claimed by two
    stored atoms keep resolving the way they do today rather than becoming
    ambiguous, because the History machinery answers first. Tightening that is
    a separate change and needs the four-outcome refactor.

    **Claims are terminal.** A payload claim yields an id and stops. It is
    never fed back into `group_occurrences`, and the *survivor* of a grouping
    is never looked up in the claims map — that would compose two declarations
    (`mention -> History survivor -> another atom's alias`), which is the
    Saqqara chain in a new place. Only the mention's own spellings are probed.
    """
    if aliases is None:
        aliases = load_aliases()

    assignments: dict = {}
    group_occurrences(
        ((t.subject, t.context) for t in raw_occurrences(atom_type)),
        prefer=lambda s: has_real_atom(atom_type, s),
        aliases=aliases,
        assignments=assignments,
    )

    ambiguous = object()
    by_key: dict = {}
    for (subject, _context), survivor in assignments.items():
        for key in alias_keys(subject):
            held = by_key.get(key)
            if held is None:
                by_key[key] = survivor
            elif held != survivor:
                by_key[key] = ambiguous

    # The alias-file lines by folded key, built once: the last-resort grouping below
    # needs only the lines that share a key with the one name it is asked about (a
    # line sharing none can neither claim it nor overlap it), and handing it every
    # line made each call rebuild every line's declaration — most of a whole
    # `index.build`. File order is kept.
    lines_by_key: dict = {}
    for i, group in enumerate(aliases):
        for key in group.keys():
            lines_by_key.setdefault(key, []).append(i)
    alias_lines = tuple(aliases)

    def _lines_for(name: str) -> list:
        hits = {i for key in alias_keys(name) for i in lines_by_key.get(key, ())}
        return [alias_lines[i] for i in sorted(hits)]

    claims_cache: dict = {}

    def _claims() -> dict:
        """The payload name index, built at most once per resolver."""
        if "map" not in claims_cache:
            claims_cache["map"] = stored_name_claims(atom_type)
        return claims_cache["map"]

    def _id_if_stored(name: str) -> Optional[str]:
        return store.atom_id(atom_type, name) if has_real_atom(atom_type, name) else None

    def _candidate_keys(name: str) -> list:
        """The name's keys, most specific first: whole string, head, inner.

        `alias_keys` answers "do these overlap?", where order is meaningless —
        but resolution takes the *first* key that answers, and iterating the
        frozenset made the answer depend on the process's string-hash seed:
        probed over eight `PYTHONHASHSEED` values, one query resolved to an
        atom under two seeds and to None under six. The order is now stated:
        the exact spelling outranks the head, the head outranks the
        parenthetical alias.
        """
        return _ordered_keys(name)

    def resolve(name: str, context: Optional[str] = None) -> Optional[str]:
        name = (name or "").strip()
        if not name:
            return None
        survivor = assignments.get((name, name_key(context) if context else None))
        if survivor is None:
            for key in _candidate_keys(name):
                held = by_key.get(key)
                if held is ambiguous:
                    return None  # two groups share this name; guessing merges cities
                if held is not None:
                    survivor = held
                    break
        if survivor is None:
            # No listed spelling keeps it company; the alias file may still
            # claim it outright (`Akhetaten` with no History mentioning Amarna).
            kept = group_occurrences(
                [(name, context)],
                prefer=lambda s: has_real_atom(atom_type, s),
                aliases=_lines_for(name),
            )
            if kept:
                survivor = kept[0][0]
        if survivor is not None:
            resolved = _id_if_stored(survivor)
            if resolved:
                return resolved
        resolved = _id_if_stored(name)
        if resolved:
            return resolved
        match = _PARENTHETICAL.match(name)
        if match:
            for spelling in (match.group("head"), match.group("inner")):
                resolved = _id_if_stored(spelling.strip())
                if resolved:
                    return resolved
        # Last resort: the names the stored atoms declare about themselves.
        # Built lazily — a caller that never reaches this step (every name
        # resolved, or the type has no atoms) does not pay to open the corpus.
        for key in _candidate_keys(name):
            claimants = _claims().get(key)
            if not claimants:
                continue
            if len(claimants) > 1:
                # Two atoms declare this name. That is a duplicate to report,
                # not a coin to flip; `duplicate_atoms` is where it surfaces.
                log.debug("%r is declared by %d stored atoms; leaving it unresolved",
                          name, len(claimants))
                return None
            return next(iter(claimants))
        return None

    return resolve


def resolve_subject(atom_type: str, subject: str, context: Optional[str] = None,
                    aliases=None) -> Optional[str]:
    """One-shot form of `subject_resolver`. Callers with many names build the
    resolver once; this exists for the single-question case and the tests."""
    return subject_resolver(atom_type, aliases=aliases)(subject, context)


def history_files() -> list:
    """The stored History atom files, for callers that need per-file lists.

    `from_history` de-duplicates across files, which is right for the work list
    and wrong for anything attributing subjects to the History that listed them
    — membership needs to know *who said so*, not just the union.
    """
    return list(_history_files())


def needing_create(atom_type: str) -> list[Topic]:
    """The create phase's actual work: listed topics without a real atom.

    `from_history` answers "what exists" — coverage and the gap report need
    every topic. Create needs "what is missing", and until this function the
    difference was nobody's job: every create path (sync, batch, dry-run plan,
    manual submit) handed the full list to code that calls the model per topic,
    so a partly generated corpus would have paid for the whole list again — and
    batch `collect` writes through `store.write_atom`, so the existing atoms
    would not merely have cost money, they would have been *replaced* by
    whatever the cheapest tier returned. A dry run announcing far more work
    items than were known to be missing is what surfaced it.

    One judgement, shared by all four call sites, on `has_real_atom` — the
    same test `group_synonyms`' `prefer` and `status --coverage` use, so the
    work list, the coverage report and the grouping cannot disagree about what
    "generated" means. Deliberate regeneration remains available and explicit:
    `python -m universe_builder.run_batch submit --list PATH` with the subjects named.
    """
    found = from_history(atom_type)
    missing = [t for t in found if not has_real_atom(atom_type, t.subject)]
    if len(missing) != len(found):
        log.warning(
            "create %s: %d of %d topics already have an atom; submitting the "
            "%d missing", atom_type, len(found) - len(missing), len(found), len(missing),
        )
    return missing


def by_context(topics: list[Topic]) -> dict[Optional[str], list[str]]:
    """Group subjects by their context, preserving order within each group.

    The batch path submits one batch per group. That is not organisational: the
    context lands in the system text, which is the cached prefix, so a batch
    mixing two contexts has two prefixes and neither is reused across the other's
    requests.
    """
    grouped: dict[Optional[str], list[str]] = {}
    for topic in topics:
        grouped.setdefault(topic.context, []).append(topic.subject)
    return grouped
