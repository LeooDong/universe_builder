log = logging.getLogger(__name__)


class _Once(logging.Filter):
    """Passes each distinct message once."""

    def __init__(self):
        super().__init__()
        self.seen = set()

    def filter(self, record: logging.LogRecord) -> bool:
        message = record.getMessage()
        if message in self.seen:
            return False
        self.seen.add(message)
        return True


@contextmanager
def warnings_once() -> Iterator[None]:
    """Within the block, a message this module logs is logged once.

    The alias file and every index atom are re-read for each atom type's work
    list, so a contradiction in the file was warned once per atom type — ten
    identical lines under history. `cli.main` and
    `run_batch.main` wrap a command in this; outside it every load warns, as
    the tests of each warning expect.
    """
    once = _Once()
    log.addFilter(once)
    try:
        yield
    finally:
        log.removeFilter(once)


@dataclass(frozen=True)
class Topic:
    """One unit of create work: what to generate, and what frames it."""

    subject: str
    #: The civilisation whose History listed this subject, e.g. "Egyptian History".
    #: None when the topic came from a flat list with no framing.
    context: Optional[str] = None

    def __str__(self) -> str:
        return self.subject if self.context is None else f"{self.subject}  ({self.context})"


def civilisations() -> list[str]:
    """The seed list the index phase generates from — `settings.HISTORY_LIST` if
    set as an override, else the active pack's `index_seed_path`. A pack with no
    seed (and no override) has nothing to generate from here."""
    path = settings.HISTORY_LIST or active_pack().index_seed_path
    if path is None:
        return []
    return [line.strip() for line in Path(path).read_text(encoding="utf-8").splitlines()
            if line.strip()]


#: Every filename generated by early versions ends in `_context_<atom_type>`.
#: The cause was `operations.create.create_atom`, which appended
#: `" (context: {atom_name})"` to the subject before handing it to `LLMCall` —
#: and `LLMCall` slugs *and hashes* the atom from that same string. Removed at
#: source, so current files do not carry it; a legacy file from
#: before then still can, and without this the model would be told "The context is egyptian history
#: context history!". Stripped when deriving the context, never on disk.
_LEGACY_CONTEXT_TAIL = re.compile(r"\s+context\s+\w+$", re.IGNORECASE)


def context_of(filename: str) -> str:
    """The civilisation a History file describes (public since v0.2.0; `_context_of`
    is the old name).

    The `History` model is five lists and nothing else — no name, no subject —
    so the file is the only record of what was asked for. Its **content id**
    hashes the seed line whole, so the seed line whose id it is gives the name
    back exactly. The slug does not: it keeps only ASCII letters and digits,
    so `Anglo-Saxon History` once came back as `anglosaxon
    history`, which no `[Anglo-Saxon History]` alias section or regime-table
    section could match (they fold to `anglo saxon history`), and the model
    was told "The context is anglosaxon history." The slug stays the fallback
    for a History whose line has left the seed list, and for legacy ids.
    """
    parsed = store.AtomName.decompose_filename(filename)
    if parsed.is_content_addressed:
        index = active_pack().index.name
        for line in civilisations():
            if store.atom_id(index, line) == parsed.padded_id:
                return store.normalise_topic(line)
    return _LEGACY_CONTEXT_TAIL.sub("", parsed.getTopic()).strip()


_context_of = context_of


#: Punctuation that carries no identity: everything outside letters and digits.
_NOISE = re.compile(r"[^a-z0-9]+")

#: A trailing parenthetical, which in this corpus declares an alternate name
#: rather than a qualifier: `Thebes (Luxor)`, `Narmer (Menes)`,
#: `Hierakonpolis (Nekhen)`. 24 of the stored entries use it.
_PARENTHETICAL = re.compile(r"^(?P<head>.*?)\s*\((?P<inner>[^)]+)\)\s*$")


#: An alias-file name wrapped in straight double quotes is **one literal
#: name** (v0.4.0): `"Unification of Upper and Lower Egypt by King Menes
#: (Narmer)"` claims that whole title and nothing else, where unquoted its
#: trailing parenthetical would also claim `narmer` — a person's name — for
#: the line. The quotes stay in `AliasGroup.names` (so a rewrite of the line
#: keeps them); `name_key` folds them away like any punctuation, and
#: `unquote` gives the spelling to hash, prefer or generate.
_QUOTED = re.compile(r'^\s*"(?P<inner>[^"]*)"\s*$')


def is_quoted(name: str) -> bool:
    """Whether an alias-file name is a quoted literal (`"Foo (Bar)"`)."""
    return bool(_QUOTED.match(name or ""))


def unquote(name: str) -> str:
    """The spelling inside a quoted alias-file name; any other name unchanged."""
    match = _QUOTED.match(name or "")
    return match.group("inner").strip() if match else name


@functools.lru_cache(maxsize=1 << 18)
def name_key(text: str) -> str:
    """Fold a name to its comparable core. Case, punctuation and diacritics
    carry no identity.

    Public since v0.2.0: every name comparison in core
    and in a pack folds through this one function, so a pack's overlap check
    and the work list's grouping cannot disagree about whether two spellings
    are one name. `_key` is the same function under its old name.

    Accented letters are folded (NFKD, combining marks dropped) rather than
    deleted, so `Châlons` keys as `chalons` and equals `Chalons`. The accent
    was once deleted with its letter — `d’état` keyed as
    `d tat` — and names in another script collapsed to whatever Latin letters
    they contained: `Kō`, `Kꜣš` and `Kατάνη` all keyed as `k`, which grouped
    Kos, Kush and Catania as one city. Folded, they key as `ko`, `k s` and
    nothing, and share nothing.

    Cached: a pure function of its argument, called millions of times
    per `index.build` on the same few hundred thousand strings (`alias_keys`, which
    returns an immutable frozenset, likewise).
    """
    import unicodedata

    folded = unicodedata.normalize("NFKD", text or "")
    folded = "".join(c for c in folded if not unicodedata.combining(c))
    return _NOISE.sub(" ", folded.lower()).strip()


#: The pre-v0.2.0 name of `name_key`, kept for callers (the history pack uses it ~49 times).
_key = name_key


@functools.lru_cache(maxsize=1 << 18)
def alias_keys(subject: str) -> frozenset:
    """Every name this entry declares, folded for comparison.

    `Thebes (Luxor)` declares *three*: the whole string, `Thebes`, and `Luxor`.
    That information is already in the corpus and was going unused — which is why
    a model answering `Thebes` produced a second atom beside the existing
    `Thebes (Luxor)` rather than resolving onto it.

    Grouping happens here, on the *work list*, and never in
    `store.normalise_topic`. That function feeds the content id, so joining names
    there would re-point every id and orphan every stored atom — its docstring
    forbids it for exactly this reason.
    """
    return frozenset(_ordered_keys((subject or "").strip()))


def _ordered_keys(name: str) -> list:
    """`name`'s keys, most specific first: the whole spelling, then for a
    trailing parenthetical its head and its inner name; empty keys dropped,
    repeats kept once. `alias_keys` is the set of these; the resolver probes
    them in this order. A quoted name (`is_quoted`) is
    literal: its one key, its parenthetical never split (v0.4.0)."""
    if is_quoted(name):
        return [k for k in (name_key(unquote(name)),) if k]
    keys = [name_key(name)]
    match = _PARENTHETICAL.match(name)
    if match:
        keys.append(name_key(match.group("head")))
        keys.append(name_key(match.group("inner")))
    return [k for k in dict.fromkeys(keys) if k]


def _declared_pair(subject: str) -> Optional[frozenset]:
    """The pair of names a parenthetical entry declares (`Thebes (Luxor)` ->
    {thebes, luxor}), or None for a bare name. The pair, not the spelling, is
    the claim: `Amarna (Akhetaten)` and `Akhetaten (Amarna)` make the same one.
    A quoted literal declares no pair."""
    if is_quoted(subject):
        return None
    match = _PARENTHETICAL.match(subject.strip())
    if not match:
        return None
    return frozenset({name_key(match.group("head")), name_key(match.group("inner"))})


def lookup_order(names) -> Iterator[tuple]:
    """`(name, folded key)` in the order the work list tries a group's
    spellings for a stored atom: as given, each folded key once (the first
    spelling with it shadows the rest; an empty key counts as one key).
    `group_occurrences` walks it to find a group's survivor, and
    `duplicates._lookup_reaches` to ask whether that walk reaches a file."""
    seen: set = set()
    for name in names:
        key = name_key(name)
        if key in seen:
            continue
        seen.add(key)
        yield name, key


def same_topic(a: str, b: str) -> bool:
    """Whether two entries name the same thing.

    Deliberately shallow: a shared declared name, not a similarity score. It will
    not catch `Akhetaten` against `Amarna (Tell el-Amarna)` — nothing in the data
    connects them — and it will wrongly join two genuinely different places that
    share a name, which becomes a real risk once more than one civilisation is
    loaded. The domain's alias file (history's is `domains/history/aliases.txt`,
    applied by `group_synonyms`) is the answer to both; this is the cheap 90% that
    needs no list to maintain.
    """
    return bool(alias_keys(a) & alias_keys(b))


@dataclass(frozen=True)
class AliasGroup:
    """One line of the alias file: names a human has declared to be one topic.

    `names` keeps the spellings as written, canonical first — the first name on
    the line is the spelling the work list emits when no stored atom decides
    otherwise. `scope` is the civilisation the line applies to, or None for
    every context: scoping is what stops `Thebes` in a Greek list from being
    joined to the Egyptian `Thebes (Luxor)`.

    `provenance` records *who said so*, and exists because a safeguard read
    this file as evidence of identity while `universe_builder duplicates --apply` was
    writing into it. Eight sections of history's alias file are headed
    "Added by `universe_builder duplicates --apply`" — records of what that command
    decided, not judgements about the world — and `duplicates._declared_same`
    was treating them as proof that a component was one subject, licensing the
    next retirement. A tool vouching for itself.

    Two values, and only one of them is evidence:

    * `asserted` — a person wrote the line, or `universe_builder collisions --via model`
      adjudicated it with the option to abstain. A claim about history.
    * `derived` — a pass recorded its own conclusion so the retired spelling
      would not regenerate. Necessary bookkeeping, and worth exactly nothing as
      an independent check.

    Grouping treats both alike, which is right: whoever wrote the line, the
    work list must honour it. Only the *safeguards* discriminate.
    """

    names: tuple
    scope: Optional[str] = None
    provenance: str = "asserted"

    def keys(self) -> frozenset:
        """Every folded key this line claims, including parenthetical splits
        (none for a quoted name)."""
        return frozenset(k for name in self.names for k in alias_keys(name))

    @property
    def spellings(self) -> tuple:
        """`names` with each quoted literal unquoted: the spellings to hash,
        prefer and generate (v0.4.0)."""
        return tuple(unquote(name) for name in self.names)

    def literal_keys(self) -> frozenset:
        """The keys of this line's quoted names. An entry whose whole spelling
        folds to one of them belongs to the line, parenthetical and all."""
        return frozenset(name_key(unquote(name)) for name in self.names if is_quoted(name))


